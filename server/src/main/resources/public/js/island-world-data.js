export const FESTIVAL_QUERY_VALUES = Object.freeze([
  'new-year','lantern','dragon-boat','mid-autumn','winter-solstice','christmas'
]);

const dtf = new Intl.DateTimeFormat('en-CA', { timeZone: TAIPEI_TZ, year: 'numeric', month: '2-digit', day: '2-digit' });

export function taipeiDateIso(ms) {
  const parts = dtf.formatToParts(ms == null ? Date.now() : ms);
  let y = '';
  let m = '';
  let d = '';
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i];
    if (p.type === 'year') y = p.value;
    else if (p.type === 'month') m = p.value;
    else if (p.type === 'day') d = p.value;
  }
  return y + '-' + m + '-' + d;
}

export function taipeiHour(ms) {
  const fmt = new Intl.DateTimeFormat('en-GB', { timeZone: TAIPEI_TZ, hour: 'numeric', hour12: false });
  return Number(fmt.format(ms == null ? Date.now() : ms));
}

export function solarTermOnDate(iso) {
  return SOLAR_TERM_BY_DATE[iso] || null;
}

export function festivalOnDate(iso) {
  return FESTIVAL_BY_DATE[iso] || null;
}

export function calendarViewForMs(ms) {
  const date = taipeiDateIso(ms);
  return {
    date: date,
    solarTerm: solarTermOnDate(date),
    festival: festivalOnDate(date)
  };
}

/** 覆寫或真實節日 id。 */
export function resolveFestivalId(ms, queryFestival) {
  const q = queryFestival == null ? '' : String(queryFestival).trim();
  if (q && FESTIVAL_QUERY_VALUES.includes(q)) return q;
  return festivalOnDate(taipeiDateIso(ms));
}

